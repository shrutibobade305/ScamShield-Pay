def is_valid_transaction_id(tx_id):
    """Validates that a transaction ID string is a well-formed token."""
    if not isinstance(tx_id, str):
        return False
    clean_id = tx_id.strip()
    return bool(re.match(r"^[A-Za-z0-9_-]{10,64}$", clean_id))


